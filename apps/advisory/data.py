_img_cache = {}


def _find_static(rel):
    from django.contrib.staticfiles import finders
    from django.conf import settings
    if not settings.DEBUG and rel in _img_cache:
        return _img_cache[rel]
    found = bool(finders.find(rel))
    _img_cache[rel] = found
    return found


def crop_image(slug):
    """A real photo dropped into static/images/krishi/<slug>.jpg|webp|png wins; otherwise the illustration."""
    for ext in ("webp", "jpg", "jpeg", "png"):
        if _find_static(f"images/krishi/{slug}.{ext}"):
            return f"images/krishi/{slug}.{ext}"
    return f"images/krishi/{slug}.svg"


def crop_og(slug):
    """Share-preview image (WhatsApp/Facebook need a raster: jpg/png)."""
    for ext in ("jpg", "jpeg", "png"):
        if _find_static(f"images/krishi/{slug}.{ext}"):
            return f"images/krishi/{slug}.{ext}"
    return f"images/krishi/og/{slug}.png"


